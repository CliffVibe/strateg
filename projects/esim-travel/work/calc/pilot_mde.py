import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
"""Пилот O3 (v2 после red-team): какую долю каннибализации k заметит рандомизированный holdout. Python stdlib.
Страны пилота: топ-5 по C090 (Турция, ОАЭ, Египет, Китай, Таиланд) = 76,1% туристических поездок 2025 (C101); влияние
«дальних» направлений проверяется разрезом по странам в самом пилоте, а не закладывается заранее.
Две разные величины роуминга (замечание red-team): R_BUYER — потерянная выручка на ОДНУ каннибализированную покупку
(C150, 2500 ₽); R_TRIP — средняя роуминговая выручка на ВСЕ поездки абонента (с нулями) и её SD — ДОПУЩЕНИЯ без данных:
доля поездок с платным роумингом 25% и разброс выручки у них тоже 2500 ₽ => R_TRIP=625 ₽, SD_TRIP≈1650 ₽.
Эффект предложения на выручку поездки: dR = - p * k * R_BUYER (ITT); оценка k по выкупившим (Вальд): k = -dR/(p*R_BUYER).
MDE по среднему (двусторонний тест, альфа 5%, мощность 80%): m = 2,8 * SD * sqrt(2/n); k_MDE = m / (p * R_BUYER).
CUPED (поправка на роуминг прошлых поездок) может снизить SD — НЕ учтено."""
from math import sqrt
Z = 1.96 + 0.84
T25, G, OP = 13_400_000, 1.05, 0.25        # C084; допущения economics.py (рост +5% к 2025, 25% поездок — наши абоненты)
COUNTRY = 0.761                              # топ-5 стран, C101
HALF = 0.5                                   # (д) пилот 6 мес из 12 без учёта сезонности
R_BUYER = 2500                               # C150
share_roam, sd_buyer = 0.25, 2500
R_TRIP = share_roam * R_BUYER
SD = sqrt(share_roam * (sd_buyer**2 + R_BUYER**2) - R_TRIP**2)
trips_year = T25 * G * OP
pool = trips_year * COUNTRY * HALF
print(f"поездок абонентов в год {trips_year/1e6:.2f} млн; в 5 странах за 6 мес {pool/1e6:.2f} млн; SD поездки {SD:.0f} ₽ (R_trip {R_TRIP:.0f})")
for share in (0.5, 1.0):
    n = pool * share / 2
    m = Z * SD * sqrt(2 / n)
    print(f"\nв эксперименте {share:.0%} пула: {n:,.0f} поездок на группу; MDE выручки {m:.1f} ₽/поездку")
    print("   k_MDE: " + "; ".join(f"p={p:.1%} -> {m/(p*R_BUYER):.0%}" for p in (0.034, 0.10)))
print()
for p in (0.034, 0.10):
    eff = p * 0.15 * R_BUYER
    n = 2 * (Z * SD / eff) ** 2
    print(f"для k=15% при p={p:.1%}: эффект {eff:.1f} ₽/поездку; нужно {n:,.0f} поездок на группу ({2*n/pool:.1f} пула пилота)")
buyers = pool * 0.5 * 0.034
print(f"\nпокупателей в группе T при p=3,4% и 50% пула: ≈ {buyers:,.0f}; опрос 1000 покупателей: ±{1.96*sqrt(.25*.75/1000)*100:.1f} п.п. (заявленная k, смещена)")
F = 20e6
print(f"затраты B 20 млн ₽ (10+10, economics.py) / поездки абонентов в год = {F/trips_year:.1f} ₽/поездку — пилот не увидит")
