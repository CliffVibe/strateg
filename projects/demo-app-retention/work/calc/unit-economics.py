"""Ценность удержания и порог окупаемости варианта C (D001). Только stdlib. Внутренних данных нет:
все входы — допущения (низ/база/верх), модель параметрическая.

Модель (простая, на 2027 год):
- Улучшение снижает ежемесячный отток среди пользователей приложения (MAU) на d (доля, 0,01 п.п. = 0.0001).
- В месяце m (1..12) отток снижен -> A*d абонентов остаются, которых иначе потеряли бы.
- Каждый такой абонент приносит выручку до конца года: (12 - m + 0.5) мес (середина месяца).
  Сумма по m = 72 абонента-месяца на единицу A*d.
- Эффект действует с 1-го месяца (оптимистично: без разгона), считается только 2027 год (без хвоста LTV в 2028+ -> консервативно).
- Ценность = A*d*72*ARPU*MARGIN. Порог: ценность = R (перераспределение ресурса, не прирост затрат; опора C066).
"""
import itertools

# --- Допущения: (низ, база, верх). "Низ/верх" = значения параметра, не благоприятность.
ASSUME = {
    "A":      (12e6, 18e6, 25e6),     # MAU приложения МегаФона, чел. (ориентиры C043, C073, C039)
    "ARPU":   (350.0, 450.0, 550.0),  # выручка на абонента в месяц, руб. (без источника)
    "CHURN":  (0.015, 0.020, 0.030),  # месячный отток, доля (без источника)
    "R":      (100e6, 200e6, 400e6),  # альтернативная стоимость ресурса в год, руб. (перераспределение)
    "MARGIN": (0.5, 0.7, 0.9),        # доля выручки, превращающаяся в маржу (без источника)
}
SUBS_MONTHS = sum(12 - m + 0.5 for m in range(1, 13))  # = 72

def value_per_pp(A, ARPU, MARGIN, pp=0.01):
    """Выручка/маржа за год, сохранённая снижением месячного оттока на pp п.п."""
    return A * (pp / 100) * SUBS_MONTHS * ARPU * MARGIN

def threshold_pp(A, ARPU, MARGIN, R):
    """Снижение месячного оттока (п.п.), при котором маржа за год = R."""
    return R / (A * SUBS_MONTHS * ARPU * MARGIN) * 100

def base():
    return {k: v[1] for k, v in ASSUME.items()}

def thr(p):
    return threshold_pp(p["A"], p["ARPU"], p["MARGIN"], p["R"])

if __name__ == "__main__":
    b = base()
    print("Абоненто-месяцев на единицу удержанных:", SUBS_MONTHS)
    print("\n== Ценность 0,01 п.п. снижения месячного оттока, млн руб./год (выручка | маржа) ==")
    for i, lab in enumerate(("низ", "база", "верх")):
        A, ARPU, M = ASSUME["A"][i], ASSUME["ARPU"][i], ASSUME["MARGIN"][i]
        rev = value_per_pp(A, ARPU, 1.0) / 1e6
        print(f"{lab:5s} A={A/1e6:.0f}млн ARPU={ARPU:.0f} маржа={M:.0%}: выручка {rev:.1f} | маржа {rev*M:.1f}")
    print("База: удержано абонентов в мес при 0,01 п.п.:", round(b["A"] * 1e-4))

    t0 = thr(b)
    print(f"\n== Порог окупаемости (база) == {t0:.4f} п.п./мес; относительно оттока {b['CHURN']:.1%}: {t0/100/b['CHURN']:.1%}")

    # лучший/худший случай: параметры, выгодные/невыгодные для окупаемости
    best = dict(A=ASSUME["A"][2], ARPU=ASSUME["ARPU"][2], MARGIN=ASSUME["MARGIN"][2], R=ASSUME["R"][0], CHURN=ASSUME["CHURN"][1])
    worst = dict(A=ASSUME["A"][0], ARPU=ASSUME["ARPU"][0], MARGIN=ASSUME["MARGIN"][0], R=ASSUME["R"][2], CHURN=ASSUME["CHURN"][1])
    print(f"Лучший случай: {thr(best):.4f} п.п.; худший: {thr(worst):.4f} п.п.")

    print("\n== Сетка R x A (остальное база), порог п.п./мес и % от базового оттока ==")
    print("R по A  " + "  ".join(f"{a/1e6:>6.0f}млн" for a in ASSUME["A"]))
    for R in ASSUME["R"]:
        row = []
        for A in ASSUME["A"]:
            p = dict(b, R=R, A=A); t = thr(p)
            row.append(f"{t:.3f}({t/100/b['CHURN']:.1%})")
        print(f"{R/1e6:>4.0f}млн  " + "  ".join(row))

    print("\n== Чувствительность: порог (п.п.) при низ/верх одного допущения, остальные база ==")
    rows = []
    for k in ("A", "ARPU", "MARGIN", "R"):
        lo = thr(dict(b, **{k: ASSUME[k][0]})); hi = thr(dict(b, **{k: ASSUME[k][2]}))
        rows.append((abs(hi - lo), k, lo, hi))
    # отток влияет на относительный порог (в % от оттока), на абсолютный — нет
    for k in ("CHURN",):
        lo = t0 / 100 / ASSUME[k][0]; hi = t0 / 100 / ASSUME[k][2]
        print(f"CHURN (только относительный порог): {lo:.1%} ... {hi:.1%} (база {t0/100/b['CHURN']:.1%})")
    for sw, k, lo, hi in sorted(rows, reverse=True):
        print(f"{k:7s} низ {lo:.4f} | верх {hi:.4f} | размах {sw:.4f} п.п. ({sw/t0:.0%} от базы)")

    # проверки
    assert abs(SUBS_MONTHS - 72) < 1e-9
    assert abs(value_per_pp(b["A"], b["ARPU"], b["MARGIN"]) * thr(b) / 0.01 - b["R"]) < 1  # ценность(порог)=R
    assert all(0 < m <= 1 for m in ASSUME["MARGIN"])
    print("\nПроверки пройдены: ценность на пороге = R; 72 абонента-месяца; маржа в (0,1].")
