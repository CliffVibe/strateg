"""MDE оттока при позднем старте (апрель): промежуточный срез 3 мес к 1 июля и полный 6 мес к 1 октября.
Две доли, alpha=0.05 двусторонний, мощность 80% (z=1.96+0.84). Аудитория 18 млн, отток 2%/мес, holdout 5% и 10%.
Плюс: какое относительное снижение оттока нужно у затронутых, если улучшения касаются доли f аудитории."""
import math
Z = 1.96 + 0.8416
A, CH = 18e6, 0.02
def mde(months, h, deff=1.0):
    p = 1 - (1 - CH) ** months
    n1, n2 = A * h, A * (1 - h)
    return Z * math.sqrt(deff * p * (1 - p) * (1 / n1 + 1 / n2)) * 100  # п.п. накопленного
for h in (0.05, 0.10):
    for mo in (3, 6):
        for d in (1, 2):
            m = mde(mo, h, d)
            p0 = 1 - (1 - CH) ** mo; p1 = p0 - m / 100; mon = (1 - (1 - p1) ** (1 / mo)) * 100
            print(f"holdout {h:.0%}, {mo} мес, DEFF {d}: MDE {m:.3f} п.п. накопл. ~ {CH*100-mon:.3f} п.п./мес (сложные проценты, как sample-size.py)")
THR = 0.092  # порог при старте в апреле, без потерь и экономии (unit-economics-net.py)
for f in (0.1, 0.2, 0.5, 1.0):
    print(f"доля затронутых {f:.0%}: нужно снижение у них {THR/f:.2f} п.п./мес = {THR/f/100/CH:.0%} от оттока")
