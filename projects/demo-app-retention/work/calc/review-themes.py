def norm(s):
    return s.lower().replace("ё", "е")


def themes(text):
    t = norm(text)
    return [k for k, rx in RX.items() if rx.search(t)]


def themes_r(text, rating):
    # «позитив» учитывается только при оценке >= 3: при 1-2 слова «хорошо/лучше» - обычно сарказм, отрицание или сравнение
    r = themes(text)
    if rating <= 2 and "позитив" in r:
        r.remove("позитив")
    return r


def wilson(k, n, z=1.96):
    if n == 0:
        return float("nan"), float("nan")
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return c - h, c + h


def ztest(k1, n1, k2, n2):
    if min(n1, n2) == 0:
        return float("nan"), float("nan")
    p = (k1 + k2) / (n1 + n2)
    se = math.sqrt(p * (1 - p) * (1 / n1 + 1 / n2))
    if se == 0:
        return 0.0, 1.0
    z = (k1 / n1 - k2 / n2) / se
    return z, math.erfc(abs(z) / math.sqrt(2))


def load():
    data = {}
    for app, f in FILES.items():
        with open(ROOT / "inputs" / f, encoding="utf-8-sig", newline="") as fh:
            rows = list(csv.DictReader(fh))
        for r in rows:
            r["rating"] = int(r["rating"])
            r["likes"] = int(r["likes"] or 0)
            r["resp"] = r["has_dev_response"].strip().lower() == "true"
            r["text"] = (r["text"] or "").strip()
            r["short"] = len(r["text"]) < 15
            r["th"] = themes_r(r["text"], r["rating"])
        data[app] = rows
    return data


def share_rows(rows, labels):
    n = len(rows)
    out = {}
    for lab in labels:
        if lab == NONE:
            k = sum(1 for r in rows if not r["th"] and not r["short"])
        elif lab == SHORT:
            k = sum(1 for r in rows if r["short"])
        else:
            k = sum(1 for r in rows if lab in r["th"])
        out[lab] = (k, n)
    return out


def fmt(k, n):
    lo, hi = wilson(k, n)
    return f"{100*k/n:.1f}% [{100*lo:.1f}-{100*hi:.1f}]"


